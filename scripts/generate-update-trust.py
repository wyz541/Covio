#!/usr/bin/env python3
"""Generate Swift trusted update keys from public metadata."""

from __future__ import annotations

import argparse
import base64
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "release/update-public-keys.json"
OUTPUT = ROOT / "macosApp/src/Updater/GeneratedUpdateTrust.swift"


def load_keys(path: pathlib.Path) -> list[tuple[str, str]]:
    raw = json.loads(path.read_text(encoding="utf-8"))
    if raw.get("schemaVersion") != 1:
        raise SystemExit("update public key schemaVersion must be 1")
    keys = raw.get("keys")
    if not isinstance(keys, list):
        raise SystemExit("update public key keys must be an array")
    result: list[tuple[str, str]] = []
    seen: set[str] = set()
    for value in keys:
        if not isinstance(value, dict):
            raise SystemExit("update public key entry must be an object")
        key_id = value.get("keyId")
        public_key = value.get("publicKey")
        if not isinstance(key_id, str) or not key_id or key_id in seen:
            raise SystemExit("update public key has an invalid or duplicate key ID")
        if not isinstance(public_key, str):
            raise SystemExit("update public key value must be base64")
        try:
            decoded = base64.b64decode(public_key, validate=True)
        except ValueError as error:
            raise SystemExit(f"invalid update public key: {key_id}") from error
        if len(decoded) != 32:
            raise SystemExit(f"update public key must be 32 bytes: {key_id}")
        seen.add(key_id)
        result.append((key_id, public_key))
    return result


def render(keys: list[tuple[str, str]]) -> str:
    lines = [
        "// This file is generated by scripts/generate-update-trust.py. Do not edit.",
        "",
        "import Foundation",
        "",
        "enum GeneratedUpdateTrust {",
        "    static let keys: [String: Data] = " + ("[:]" if not keys else "["),
    ]
    for key_id, public_key in keys:
        escaped = key_id.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(
            f'        "{escaped}": Data(base64Encoded: "{public_key}") ?? Data(),'
        )
    if keys:
        lines.append("    ]")
    lines.extend(["}", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render(load_keys(SOURCE))
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
            print("Generated update trust keys are stale", file=sys.stderr)
            return 1
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
