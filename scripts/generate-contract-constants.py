def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    if hasattr(sys.stderr, "reconfigure"):
        sys.stderr.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="不写文件，只报告是否有差异")
    args = parser.parse_args()

    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))
    outputs = {
        COPY_OUT: generate_copy(contract),
        TOKENS_OUT: generate_tokens(contract),
        SEMANTICS_OUT: generate_semantics(contract),
        RUST_MOTION_OUT: generate_rust_motion(contract),
        RUST_DESIGN_OUT: generate_rust_design(contract),
        COMPOSE_OUT: generate_compose(contract),
    }

    if args.check:
        stale = [
            path
            for path, text in outputs.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        if stale:
            for path in stale:
                print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
            print(
                "重跑 python3 scripts/generate-contract-constants.py 重新生成。",
                file=sys.stderr,
            )
            return 1
        print(
            f"合同常量是最新的：{len(outputs)} 个文件，"
            f"{len(contract['copy'])} 条文案，"
            f"{len(contract['platformFonts'])} 个平台字体映射。"
        )
        return 0

    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
