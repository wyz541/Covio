def identifier(key: str) -> str:
    """`copy/overview/helper/installed` -> `copyOverviewHelperInstalled`。"""
    parts = re.split(r"[/\-]", key)
    name = parts[0] + "".join(part[:1].upper() + part[1:] for part in parts[1:])
    return re.sub(r"[^0-9A-Za-z_]", "", name)


def swift_string(text: str) -> str:
    escaped = (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def rust_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def kotlin_string(text: str) -> str:
    escaped = (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("$", "\\$")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def swift_string_array(values: list[str]) -> str:
    return "[" + ", ".join(swift_string(value) for value in values) + "]"


def rust_string_array(values: list[str]) -> str:
    return "&[" + ", ".join(rust_string(value) for value in values) + "]"


def kotlin_string_list(values: list[str]) -> str:
    if not values:
        return "emptyList()"
    return "listOf(" + ", ".join(kotlin_string(value) for value in values) + ")"

def rust_identifier(key: str) -> str:
    """Convert a motion token key into a stable Rust constant name."""
    parts = re.split(r"[/\-@.]", key)
    if parts[:2] == ["token", "motion"]:
        parts = parts[2:]
    return "_".join(part.upper() for part in parts)


def rust_duration(value: float) -> str:
    """Render a millisecond value as a Rust Duration expression."""
    if float(value).is_integer():
        return f"Duration::from_millis({int(value)})"
    return f"Duration::from_micros({round(float(value) * 1000)})"


def rust_float(value: float) -> str:
    return repr(float(value))


def parse_hex_color(value: str) -> tuple[int, int, int, int]:
    text = value.removeprefix("#")
    if len(text) == 6:
        text += "FF"
    if len(text) != 8:
        raise ValueError(f"unsupported color value: {value}")
    return tuple(int(text[index:index + 2], 16) for index in range(0, 8, 2))  # type: ignore[return-value]


def rust_design_color(value: str) -> str:
    red, green, blue, alpha = parse_hex_color(value)
    return (
        "DesignColor { "
        f"red: 0x{red:02X}, green: 0x{green:02X}, blue: 0x{blue:02X}, alpha: 0x{alpha:02X}"
        " }"
    )


def kotlin_optional_string(value: str | None) -> str:
    return "null" if value is None else kotlin_string(value)


def skip_rustfmt_items(lines: list[str]) -> list[str]:
    """Keep generated top-level items stable without unstable inner attributes."""
    output: list[str] = []
    for line in lines:
        if re.match(r"^(?:pub )?(?:const|static|struct|fn) ", line):
            output.append("#[rustfmt::skip]")
        output.append(line)
    return output


def generate_copy(contract: dict) -> str:
    entries = contract["copy"]
    lines = [HEADER, "import Foundation", ""]
    lines.append("/// 设计合同 `copy` 段的全部文案。")
    lines.append("///")
    lines.append("/// 键名就是合同里的键路径。`DesignContractTests` 逐条比对，")
    lines.append("/// 所以这里的值不能手改。")
    lines.append("enum ContractCopy {")

    names = []
    for key in sorted(entries):
        value = entries[key]
        name = identifier(key)
        names.append(name)
        lines.append(f"    /// `{key}`")
        lines.append(
            f"    static let {name} = LocalizedCopy("
            f"key: {swift_string(key)}, "
            f"en: {swift_string(value['en'])}, "
            f"zhHans: {swift_string(value['zh-Hans'])})"
        )
    lines.append("")
    lines.append("    /// 全部条目。供测试遍历。")
    lines.append("    static let all: [LocalizedCopy] = [")
    for name in names:
        lines.append(f"        {name},")
    lines.append("    ]")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


