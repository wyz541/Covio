#!/usr/bin/env python3
"""Generate typed Rust Workbench interaction specifications from macOS JSON."""

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "docs" / "macos-interaction-contract.json"
OUTPUT = ROOT / "rust" / "crates" / "covio-core" / "src" / "workbench_interaction.rs"

HEADER = """// This file is generated by scripts/generate-workbench-interaction.py. Do not edit it by hand.
// Source of truth: docs/macos-interaction-contract.json.
"""

ALIGNMENT = {"topCenter": "TopCenter"}
DISPLAY_SELECTION = {"pointerDisplayThenMainFallback": "PointerDisplayThenMainFallback"}
TRIGGER_SHAPE = {"notch": "Notch", "centeredBand": "CenteredBand"}
DIRECTION = {"topToBottom": "TopToBottom", "bottomToTop": "BottomToTop"}
REDUCED_EFFECT = {"opacity": "Opacity"}
PLATFORM = {"windows": "Windows"}


def rust_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def rust_float(value: float) -> str:
    number = float(value)
    if number.is_integer():
        return f"{int(number)}.0"
    return repr(number)


def variant(mapping: dict[str, str], value: str, path: str) -> str:
    try:
        return mapping[value]
    except KeyError as error:
        raise ValueError(f"unsupported {path}: {value!r}") from error


def easing_spec(value: dict, path: str) -> str:
    kind = value["type"]
    if kind == "spring":
        return (
            "EasingSpec::Spring {\n"
            f"            response_seconds: {rust_float(value['responseSeconds'])},\n"
            f"            damping_fraction: {rust_float(value['dampingFraction'])},\n"
            "        }"
        )
    if kind == "easeOut":
        return "EasingSpec::EaseOut"
    raise ValueError(f"unsupported {path}.type: {kind!r}")


def generate(contract: dict) -> str:
    trigger_geometry = contract["trigger"]["geometry"]
    reveal = contract["reveal"]
    conceal = contract["conceal"]
    reduced = contract["reducedMotion"]
    geometry = contract["geometry"]
    panel_width = int(geometry["panelWidthPoints"])
    panel_radius = int(geometry["panelCornerRadiusPoints"])
    if panel_width <= 0 or panel_width > 65535:
        raise ValueError("panelWidthPoints must fit u16")
    if panel_radius <= 0 or panel_radius > 255:
        raise ValueError("panelCornerRadiusPoints must fit u8")

    lines = [
        HEADER,
        "use std::time::Duration;",
        "",
        f"pub const WORKBENCH_PANEL_WIDTH_POINTS: u16 = {panel_width};",
        f"pub const WORKBENCH_PANEL_CORNER_RADIUS_POINTS: u8 = {panel_radius};",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub enum TriggerAlignment {",
        "    TopCenter,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub enum DisplaySelection {",
        "    PointerDisplayThenMainFallback,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub enum TriggerShape {",
        "    Notch,",
        "    CenteredBand,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub enum TransitionDirection {",
        "    TopToBottom,",
        "    BottomToTop,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq)]",
        "pub enum EasingSpec {",
        "    Spring {",
        "        response_seconds: f64,",
        "        damping_fraction: f64,",
        "    },",
        "    EaseOut,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub enum ReducedMotionEffect {",
        "    Opacity,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub enum Platform {",
        "    Windows,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq)]",
        "pub struct TriggerGeometrySpec {",
        "    pub alignment: TriggerAlignment,",
        "    pub display_selection: DisplaySelection,",
        "    pub notched_display: TriggerShape,",
        "    pub notchless_display: TriggerShape,",
        "    pub notchless_width_points: f64,",
        "    pub notchless_height_points: f64,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq)]",
        "pub struct TriggerSpec {",
        "    pub dwell_ms: f64,",
        "    pub cooldown_ms: f64,",
        "    pub pointer_exit_collapse_ms: f64,",
        "    pub geometry: TriggerGeometrySpec,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq)]",
        "pub struct TransitionSpec {",
        "    pub direction: TransitionDirection,",
        "    pub duration_ms: f64,",
        "    pub easing: EasingSpec,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq)]",
        "pub struct ReducedMotionSpec {",
        "    pub duration_ms: f64,",
        "    pub effect: ReducedMotionEffect,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq)]",
        "pub struct GeometrySpec {",
        "    pub panel_width_points: f64,",
        "    pub panel_corner_radius_points: f64,",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq)]",
        "pub struct PlatformOverrideSpec {",
        "    pub id: &'static str,",
        "    pub platform: Platform,",
        "    pub field: &'static str,",
        "    pub value: f64,",
        "    pub reason: &'static str,",
        "    pub evidence: &'static [&'static str],",
        "}",
        "",
        "#[derive(Debug, Clone, Copy, PartialEq)]",
        "pub struct WorkbenchInteractionSpec {",
        "    pub contract_id: &'static str,",
        "    pub schema_version: &'static str,",
        "    pub trigger: TriggerSpec,",
        "    pub reveal: TransitionSpec,",
        "    pub conceal: TransitionSpec,",
        "    pub reduced_motion: ReducedMotionSpec,",
        "    pub geometry: GeometrySpec,",
        "    pub platform_overrides: &'static [PlatformOverrideSpec],",
        "}",
        "",
    ]

    override_lines = []
    for item in contract["platformOverrides"]:
        override_lines.extend([
            "    PlatformOverrideSpec {",
            f"        id: {rust_string(item['id'])},",
            f"        platform: Platform::{variant(PLATFORM, item['platform'], 'platformOverrides.platform')},",
            f"        field: {rust_string(item['field'])},",
            f"        value: {rust_float(item['value'])},",
            f"        reason: {rust_string(item['reason'])},",
        ])
        if len(item["evidence"]) == 1:
            override_lines.append(f"        evidence: &[{rust_string(item['evidence'][0])}],")
        else:
            override_lines.append("        evidence: &[")
            for evidence in item["evidence"]:
                override_lines.append(f"            {rust_string(evidence)},")
            override_lines.append("        ],")
        override_lines.append("    },")

    if override_lines:
        lines.append("pub static WORKBENCH_PLATFORM_OVERRIDES: &[PlatformOverrideSpec] = &[")
        lines.extend(override_lines)
        lines.extend(["];", ""])
        overrides_expr = "WORKBENCH_PLATFORM_OVERRIDES"
    else:
        overrides_expr = "&[]"

    lines.extend([
        "pub static WORKBENCH_INTERACTION: WorkbenchInteractionSpec = WorkbenchInteractionSpec {",
        f"    contract_id: {rust_string(contract['contractId'])},",
        f"    schema_version: {rust_string(contract['schemaVersion'])},",
        "    trigger: TriggerSpec {",
        f"        dwell_ms: {rust_float(contract['trigger']['dwellMs'])},",
        f"        cooldown_ms: {rust_float(contract['trigger']['cooldownMs'])},",
        f"        pointer_exit_collapse_ms: {rust_float(contract['trigger']['pointerExitCollapseMs'])},",
        "        geometry: TriggerGeometrySpec {",
        f"            alignment: TriggerAlignment::{variant(ALIGNMENT, trigger_geometry['alignment'], 'trigger.geometry.alignment')},",
        f"            display_selection: DisplaySelection::{variant(DISPLAY_SELECTION, trigger_geometry['displaySelection'], 'trigger.geometry.displaySelection')},",
        f"            notched_display: TriggerShape::{variant(TRIGGER_SHAPE, trigger_geometry['notchedDisplay'], 'trigger.geometry.notchedDisplay')},",
        f"            notchless_display: TriggerShape::{variant(TRIGGER_SHAPE, trigger_geometry['notchlessDisplay'], 'trigger.geometry.notchlessDisplay')},",
        f"            notchless_width_points: {rust_float(trigger_geometry['notchlessWidthPoints'])},",
        f"            notchless_height_points: {rust_float(trigger_geometry['notchlessHeightPoints'])},",
        "        },",
        "    },",
        "    reveal: TransitionSpec {",
        f"        direction: TransitionDirection::{variant(DIRECTION, reveal['direction'], 'reveal.direction')},",
        f"        duration_ms: {rust_float(reveal['durationMs'])},",
        f"        easing: {easing_spec(reveal['easing'], 'reveal.easing')},",
        "    },",
        "    conceal: TransitionSpec {",
        f"        direction: TransitionDirection::{variant(DIRECTION, conceal['direction'], 'conceal.direction')},",
        f"        duration_ms: {rust_float(conceal['durationMs'])},",
        f"        easing: {easing_spec(conceal['easing'], 'conceal.easing')},",
        "    },",
        "    reduced_motion: ReducedMotionSpec {",
        f"        duration_ms: {rust_float(reduced['durationMs'])},",
        f"        effect: ReducedMotionEffect::{variant(REDUCED_EFFECT, reduced['effect'], 'reducedMotion.effect')},",
        "    },",
        "    geometry: GeometrySpec {",
        f"        panel_width_points: {rust_float(geometry['panelWidthPoints'])},",
        f"        panel_corner_radius_points: {rust_float(geometry['panelCornerRadiusPoints'])},",
        "    },",
        f"    platform_overrides: {overrides_expr},",
        "};",
        "",
        "impl WorkbenchInteractionSpec {",
        "    /// Returns the explicit numeric override for one platform field.",
        "    #[must_use]",
        "    pub fn platform_value(&self, platform: Platform, field: &str) -> Option<f64> {",
        "        self.platform_overrides",
        "            .iter()",
        "            .find(|entry| entry.platform == platform && entry.field == field)",
        "            .map(|entry| entry.value)",
        "    }",
        "",
        "    /// Returns the effective reveal duration.",
        "    #[must_use]",
        "    pub fn reveal_duration(&self, platform: Platform) -> Duration {",
        "        duration_from_millis(",
        "            self.platform_value(platform, \"reveal.durationMs\")",
        "                .unwrap_or(self.reveal.duration_ms),",
        "        )",
        "    }",
        "",
        "    /// Returns the effective conceal duration.",
        "    #[must_use]",
        "    pub fn conceal_duration(&self, platform: Platform) -> Duration {",
        "        duration_from_millis(",
        "            self.platform_value(platform, \"conceal.durationMs\")",
        "                .unwrap_or(self.conceal.duration_ms),",
        "        )",
        "    }",
        "",
        "    /// Returns the effective reduced-motion duration.",
        "    #[must_use]",
        "    pub fn reduced_motion_duration(&self, platform: Platform) -> Duration {",
        "        duration_from_millis(",
        "            self.platform_value(platform, \"reducedMotion.durationMs\")",
        "                .unwrap_or(self.reduced_motion.duration_ms),",
        "        )",
        "    }",
        "",
        "    /// Returns the effective pointer-exit collapse delay.",
        "    #[must_use]",
        "    pub fn pointer_exit_collapse_duration(&self, platform: Platform) -> Duration {",
        "        duration_from_millis(",
        "            self.platform_value(platform, \"trigger.pointerExitCollapseMs\")",
        "                .unwrap_or(self.trigger.pointer_exit_collapse_ms),",
        "        )",
        "    }",
        "",
        "    /// Returns the effective trigger dwell duration.",
        "    #[must_use]",
        "    pub fn trigger_dwell_duration(&self, platform: Platform) -> Duration {",
        "        duration_from_millis(",
        "            self.platform_value(platform, \"trigger.dwellMs\")",
        "                .unwrap_or(self.trigger.dwell_ms),",
        "        )",
        "    }",
        "",
        "    /// Returns the effective trigger cooldown duration.",
        "    #[must_use]",
        "    pub fn trigger_cooldown_duration(&self, platform: Platform) -> Duration {",
        "        duration_from_millis(",
        "            self.platform_value(platform, \"trigger.cooldownMs\")",
        "                .unwrap_or(self.trigger.cooldown_ms),",
        "        )",
        "    }",
        "",
        "    /// Returns the effective Workbench panel width.",
        "    #[must_use]",
        "    pub fn panel_width_points(&self, platform: Platform) -> f64 {",
        "        self.platform_value(platform, \"geometry.panelWidthPoints\")",
        "            .unwrap_or(self.geometry.panel_width_points)",
        "    }",
        "",
        "    /// Returns the effective Workbench panel corner radius.",
        "    #[must_use]",
        "    pub fn panel_corner_radius_points(&self, platform: Platform) -> f64 {",
        "        self.platform_value(platform, \"geometry.panelCornerRadiusPoints\")",
        "            .unwrap_or(self.geometry.panel_corner_radius_points)",
        "    }",
        "}",
        "",
        "fn duration_from_millis(value: f64) -> Duration {",
        "    Duration::from_secs_f64(value / 1000.0)",
        "}",
        "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    contract = json.loads(CONTRACT.read_text(encoding="utf-8"))
    generated = generate(contract)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            print(f"stale: {OUTPUT.relative_to(ROOT)}", file=sys.stderr)
            print("Run python3 scripts/generate-workbench-interaction.py.", file=sys.stderr)
            return 1
        print("Workbench interaction Rust spec is current.")
        return 0

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
